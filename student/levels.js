/* ============================================================================
   levels.js  —  THE LEVELS, DRAWN AS TEXT
   ============================================================================

   Each level is a picture made of characters. One character = one block.
   The game reads these pictures and builds the world from them.

   QUICK KEY  (the full list, including anything you add, is LEGEND in
   entities.js)

     .   empty air            #   solid block          =   ledge (jump up
     P   player start         G   goal flag                through it,
     ^   spikes               o   coin                     land on top)
     *   gem                  b   speed boots
     f   feather (big jump)   E   walker enemy
     F   flying enemy         H   hopping enemy

   RULES THE GAME CHECKS FOR YOU
     - exactly one P and at least one G in every level
     - every character must be in the LEGEND
     - rows can be different lengths; short rows are filled with air

   TO SEE A CHANGE: save this file, then reload the game page
   (Ctrl+R, or Cmd+R on a Mac). Pressing R in the game only restarts the
   level; it does not re-read this file.
   ========================================================================= */


